/**
 * Build-time content snapshot.
 *
 * Fetches every read endpoint from the API and writes:
 *   - src/generated/content.ts   → typed `snapshot` used as SSG/initial data
 *   - src/generated/routes.json  → concrete /projects/:slug and /blog/:slug paths
 *
 * If the API is unreachable, it writes empty stubs so the build still succeeds
 * (dynamic pages then fall back to client-side rendering).
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const outDir = join(here, "..", "src", "generated");
const publicDir = join(here, "..", "public");
const base = process.env.VITE_API_URL ?? "http://localhost:4000";

// The API is on a free tier that cold-starts for up to ~a minute, so give each
// request a generous timeout and retry a few times before giving up.
const TIMEOUT_MS = 60_000;
const ATTEMPTS = 3;

async function get(path) {
  let lastErr;
  for (let attempt = 1; attempt <= ATTEMPTS; attempt++) {
    try {
      const res = await fetch(base + path, { signal: AbortSignal.timeout(TIMEOUT_MS) });
      if (!res.ok) throw new Error(`${path} → ${res.status}`);
      return await res.json();
    } catch (err) {
      lastErr = err;
      if (attempt < ATTEMPTS) await new Promise((r) => setTimeout(r, 2_000 * attempt));
    }
  }
  throw lastErr;
}

async function main() {
  mkdirSync(outDir, { recursive: true });

  let snapshot = {
    projects: [],
    posts: [],
    fullPosts: [],
    experience: [],
    skills: { categories: [], highlightedIntegrations: [] },
  };
  let routes = [];

  try {
    const [projects, posts, experience, skills] = await Promise.all([
      get("/api/projects"),
      get("/api/posts"),
      get("/api/experience"),
      get("/api/skills"),
    ]);

    // A single flaky post detail must not blank the whole snapshot — keep the
    // ones that resolved; the rest fall back to client-side rendering.
    const settled = await Promise.allSettled(posts.map((p) => get(`/api/posts/${p.slug}`)));
    const fullPosts = settled
      .filter((r) => r.status === "fulfilled")
      .map((r) => r.value);
    const failed = settled.length - fullPosts.length;

    snapshot = { projects, posts, fullPosts, experience, skills };
    routes = [
      ...projects.map((p) => `/projects/${p.slug}`),
      ...posts.map((p) => `/blog/${p.slug}`),
    ];
    console.log(
      `snapshot: ${projects.length} projects, ${posts.length} posts` +
        (failed ? ` (${failed} post bodies failed)` : "") +
        `, ${experience.length} experience, ${skills.categories.length} skill groups`
    );
  } catch (err) {
    if (process.env.VERCEL) {
      // Shipping an empty prerender to production is worse than keeping the
      // previous deployment live, so fail the deploy build instead.
      console.error(`snapshot: API unreachable at ${base} (${err.message}). Failing the Vercel build.`);
      process.exit(1);
    }
    console.warn(`snapshot: API unreachable at ${base} (${err.message}). Writing empty stub.`);
  }

  writeFileSync(
    join(outDir, "content.ts"),
    "// AUTO-GENERATED by scripts/snapshot-content.mjs — do not edit.\n" +
      "import type { Snapshot } from \"@/lib/types\";\n\n" +
      `export const snapshot: Snapshot = ${JSON.stringify(snapshot, null, 2)};\n`
  );
  writeFileSync(join(outDir, "routes.json"), JSON.stringify(routes, null, 2) + "\n");
  mkdirSync(publicDir, { recursive: true });
  writeSitemap(snapshot);
  writeRss(snapshot);
}

const site = (process.env.PUBLIC_SITE_URL ?? "https://thanveerahammed.in").replace(/\/+$/, "");
const esc = (v) =>
  String(v)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
const parseDate = (d) => {
  const t = new Date(d);
  return Number.isNaN(t.getTime()) ? undefined : t;
};

/**
 * Writes public/sitemap.xml so it ships as a static file from the CDN. Proxying it
 * (and robots.txt) to the free-tier API risked 30s+ cold-start timeouts, which
 * Googlebot treats as the site being blocked.
 */
function writeSitemap(snap) {
  const iso = (d) => parseDate(d)?.toISOString().slice(0, 10);
  const entries = [
    ...["", "/projects", "/blog", "/resume", "/uses", "/now", "/privacy"].map((p) => ({ loc: site + p })),
    ...snap.projects.map((p) => ({ loc: `${site}/projects/${p.slug}` })),
    ...snap.posts.map((p) => ({ loc: `${site}/blog/${p.slug}`, lastmod: iso(p.date) })),
  ];
  const body = entries
    .map(
      (e) =>
        `  <url>\n    <loc>${esc(e.loc)}</loc>${e.lastmod ? `\n    <lastmod>${e.lastmod}</lastmod>` : ""}\n  </url>`
    )
    .join("\n");
  writeFileSync(
    join(publicDir, "sitemap.xml"),
    `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${body}\n</urlset>\n`
  );
}

/**
 * Writes public/rss.xml for the same reason as the sitemap: feed readers polling a
 * cold-starting API would time out. Mirrors renderRss() in
 * server/src/services/feed.service.ts (which still serves /rss.xml on the API host).
 */
function writeRss(snap) {
  const items = snap.posts
    .map((p) => {
      const link = esc(`${site}/blog/${p.slug}`);
      const pub = parseDate(p.date);
      return (
        `\n    <item>\n      <title>${esc(p.title)}</title>\n      <link>${link}</link>\n` +
        `      <guid isPermaLink="true">${link}</guid>\n` +
        (pub ? `      <pubDate>${pub.toUTCString()}</pubDate>\n` : "") +
        `      <description>${esc(p.description)}</description>\n    </item>`
      );
    })
    .join("");
  writeFileSync(
    join(publicDir, "rss.xml"),
    `<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">
  <channel>
    <title>Thanveer Ahammed N — Blog</title>
    <link>${esc(`${site}/blog`)}</link>
    <atom:link href="${esc(`${site}/rss.xml`)}" rel="self" type="application/rss+xml" />
    <description>Notes on software engineering, system design, AI integration, and automation.</description>
    <language>en-us</language>
    <lastBuildDate>${new Date().toUTCString()}</lastBuildDate>${items}
  </channel>
</rss>
`
  );
}

main();
