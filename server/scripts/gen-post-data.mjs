/**
 * Generates src/seed/data/posts.ts from the editable markdown in
 * seed/content/blog/*.mdx so the blog content is bundled into the compiled
 * server (no filesystem reads at runtime, works the same on Render).
 *
 * Regenerate after editing a post:  npm run gen:posts --workspace server
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import matter from "gray-matter";
import readingTime from "reading-time";

const here = dirname(fileURLToPath(import.meta.url));
const BLOG_DIR = join(here, "..", "seed", "content", "blog");
const OUT = join(here, "..", "src", "seed", "data", "posts.ts");

const posts = readdirSync(BLOG_DIR)
  .filter((f) => /\.mdx?$/.test(f))
  .map((file) => {
    const raw = readFileSync(join(BLOG_DIR, file), "utf8");
    const { data, content } = matter(raw);
    const body = content.trim();
    return {
      slug: file.replace(/\.mdx?$/, ""),
      title: String(data.title),
      description: String(data.description),
      date: String(data.date),
      tags: data.tags ?? [],
      readingTime: readingTime(body).text,
      content: body,
    };
  })
  .sort((a, b) => (a.date < b.date ? 1 : -1));

const file =
  "// AUTO-GENERATED by scripts/gen-post-data.mjs from seed/content/blog/*.mdx — do not edit.\n" +
  "// Regenerate: npm run gen:posts --workspace server\n\n" +
  "export type SeedPost = {\n" +
  "  slug: string;\n  title: string;\n  description: string;\n  date: string;\n" +
  "  tags: string[];\n  readingTime: string;\n  content: string;\n};\n\n" +
  `export const posts: SeedPost[] = ${JSON.stringify(posts, null, 2)};\n`;

writeFileSync(OUT, file);
console.log(`wrote ${OUT} (${posts.length} posts)`);
